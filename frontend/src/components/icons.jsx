/** Deterministic gradient avatar from an address (no external identicon lib). */
export function AddressAvatar({ address, size = 40 }) {
  const a = (address || "0x0").toLowerCase();
  const h1 = parseInt(a.slice(2, 6), 16) % 360;
  const h2 = (h1 + 60 + (parseInt(a.slice(6, 8), 16) % 120)) % 360;
  return (
    <span
      className="avatar"
      style={{ width: size, height: size, background: `linear-gradient(135deg, hsl(${h1} 80% 60%), hsl(${h2} 75% 45%))` }}
    />
  );
}
